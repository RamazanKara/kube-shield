	buf.WriteString("| 60-69 | D |\n")
	buf.WriteString("| 0-59 | F |\n\n")

	buf.WriteString("## Documentation Maintenance\n\n")
	buf.WriteString("When adding, removing, or changing a check:\n\n")
	buf.WriteString("- Keep `CheckID` stable unless the behavior is intentionally replaced.\n")
	buf.WriteString("- Update the rule catalog in `internal/scanner/engine/rules.go`.\n")
	buf.WriteString("- Run `go generate ./...` to refresh this file.\n")
	buf.WriteString("- Update README scanner counts when counts change.\n")
	buf.WriteString("- Add or update unit tests and E2E fixtures.\n")
