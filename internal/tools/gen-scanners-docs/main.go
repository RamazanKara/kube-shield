	buf.WriteString("| Level | Meaning |\n")
	buf.WriteString("|-------|---------|\n")
	buf.WriteString("| Critical | Direct compromise or full cluster-control path is plausible |\n")
	buf.WriteString("| High | Significant security weakness or strong escalation path |\n")
	buf.WriteString("| Medium | Defense-in-depth gap or risky configuration |\n")
	buf.WriteString("| Low | Best-practice deviation |\n")
	buf.WriteString("| Info | Operational observation |\n\n")
	buf.WriteString("Severity is assigned by expected blast radius and exploitability. If a finding depends heavily on local policy or compensating controls, prefer the lower severity and explain the risk clearly in remediation text.\n\n")

	for _, def := range scanner.BuiltIns() {
		writeScannerSection(&buf, def)
	}

	buf.WriteString("## Scoring\n\n")
	buf.WriteString("The score is calculated from the filtered, de-duplicated finding set:\n\n")
	buf.WriteString("```text\n")
	buf.WriteString("score = 100 - (critical*10 + high*5 + medium*2 + low*0.5)\n")
	buf.WriteString("```\n\n")
	buf.WriteString("Info findings do not reduce the score. Scores are clamped at zero. Known CIS/core overlaps are counted once in the summary; raw findings remain in JSON and SARIF output.\n\n")
	buf.WriteString("| Score | Grade |\n")
	buf.WriteString("|-------|-------|\n")
	buf.WriteString("| 90-100 | A |\n")
